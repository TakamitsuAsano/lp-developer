import streamlit as st

# ページ設定
st.set_page_config(page_title="LPプロンプトジェネレーター", layout="wide")

st.title("🚀 LP作成用プロンプトジェネレーター")
st.markdown("イベント情報を入力すると、Geminiにそのまま貼り付けて高品質なLP（HTMLファイル）を作成できるプロンプトを自動生成します。")

# 画面を2カラムに分割
col1, col2 = st.columns([1, 1])

with col1:
    st.subheader("📝 1. イベント情報の入力")
    
    event_title = st.text_input("イベントタイトル", "KURUME SPACE INNOVATION 2026")
    event_date = st.text_input("日時", "2026.06.01 MON 15:00 - 18:10")
    event_venue = st.text_input("会場・アクセス", "久留米商工会議所（久留米商工会館）5階 大ホール")
    
    target_audience = st.text_area("ターゲット層", 
        "・宇宙を活かして新しい取り組みに挑戦したいと考えている企業・自治体・教育研究機関の皆さま\n"
        "（農業、土木、建築、不動産、モビリティ、観光、ものづくりなど幅広く歓迎）\n"
        "・宇宙を活かした社会課題解決などに興味関心のある学生の皆さま"
    )
    
    tone_manner = st.selectbox("トンマナ（デザインの方向性）", [
        "シックでクリエイティブ（ダークトーン×マガジンスタイル）",
        "クリーンで先進的（白背景×ブルー系・IT系）",
        "温かみと親しみ（アースカラー・地域密着型）"
    ])
    
    organizers = st.text_input("主催 / 共催など", "主催 : 久留米市、準天頂衛星システムサービス株式会社（QSS）、一般社団法人クロスユー（事務局）")
    
    agenda = st.text_area("アジェンダと登壇者（CSVやテキストでベタ打ち）", 
        "15:00 開会挨拶\n"
        "15:05 ご挨拶\n"
        "15:10 【インプットセッション】三上さん\n"
        "15:25 【インプットセッション】山崎さん\n"
        "16:20 【パネルディスカッション】..."
    )
    
    extra_notes = st.text_area("その他の特記事項（Q&A、熱い想い、特別ゲスト情報など）", 
        "今回のイベントは一発ものではなく、ある意味ではキックオフ的な位置付けで、"
        "これから年間に複数回事業化を本気で考えるコミュニティを立ち上げるニュアンスを入れてほしい。"
    )

# プロンプトのテンプレートを構築
prompt_template = f"""
あなたは非常に優秀なWebデザイナー・フロントエンドエンジニアです。
以下のイベント情報と要件に基づき、洗練されたランディングページ（LP）のHTMLファイルを1つ作成してください。

【デザイン要件】
・フルスクリーンレイアウト、ワンカラムレイアウトを採用すること
・ビジュアルドリブンでマガジンスタイルのUI（CSSはTailwind CSSのCDNを使用）
・トンマナ設定: {tone_manner}
・文字も写真も大きめで、カッコよく、デザイン性重視のフォント（Google Fonts等）を使用すること
・外部画像を使用する場合、リンク切れ時に別のダミー画像が表示される `onerror` 属性は絶対に使用しないこと

【イベント基本情報】
・タイトル: {event_title}
・日時: {event_date}
・会場: {event_venue}
・対象者: 
{target_audience}
・主催: {organizers}

【アジェンダ・登壇者】
以下の進行表に沿って、タイムライン風のカッコいいデザインでセクションを作成してください。
{agenda}

【特別要件・イベントの趣旨】
{extra_notes}

【出力ルール】
・HTML、CSS（Tailwind）、JavaScript（必要であれば）をすべて1つのHTMLファイルにまとめて出力してください。
・コードブロックで囲んで出力してください。
"""

with col2:
    st.subheader("✨ 2. 生成されたプロンプト")
    st.markdown("以下のテキストを右上のコピーボタンでコピーし、**Gemini**に貼り付けてください。")
    
    # st.codeを使うと自動でコピーボタンが付与されます
    st.code(prompt_template, language="text")